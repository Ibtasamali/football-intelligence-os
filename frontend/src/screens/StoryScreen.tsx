import { useEffect, useState } from "react";
import { take } from "../lib/prefetch";
import { motion } from "framer-motion";
import { BookOpen, Crown, Loader2, Swords, Target, Volume2 } from "lucide-react";
import { api } from "../lib/api";
import { useStore } from "../lib/store";
import { replayInsight } from "../lib/replay";
import { speak } from "../lib/voice";
import { Badge } from "../components/ui";

let handled = 0;  // each auto-demo request runs once (StrictMode re-runs effects)

export default function StoryScreen() {
  const { matchId, insights, teams, profile } = useStore();
  const [story, setStory] = useState<any>(null);
  const [busy, setBusy] = useState(false);
  const gen = async () => {
    setBusy(true);
    try { setStory(await take(`story:${matchId}`, () => api.story(matchId))); useStore.getState().set({ storyReadyAt: Date.now() }); } finally { setBusy(false); }
  };
  const storyRequest = useStore((s) => s.storyRequest);
  useEffect(() => { if (storyRequest > handled) { handled = storyRequest; gen(); } }, [storyRequest]);
  const potm = story?.facts?.player_of_the_match;
  return (
    <div className="h-full overflow-y-auto p-6">
      <div className="mx-auto max-w-6xl">
        <div className="flex items-end justify-between">
          <div>
            <div className="label text-cyan-300">Storytelling agent · large model over verified facts</div>
            <h1 className="mt-1 font-display text-3xl font-bold text-white">{story?.headline ?? "The story of the match"}</h1>
            {story && <div className="mt-1 text-sm text-slate-400">{story.facts.score} · generated by {story.model} · verification {story.verification?.passed ? "passed" : "corrected"}</div>}
          </div>
          <div className="flex gap-2">
            {story && <button className="btn" onClick={() => speak(`${story.headline}. ${story.how_won}`, profile.persona)}><Volume2 size={14} /> Narrate</button>}
            <button className="btn-primary" onClick={gen} disabled={busy}>{busy ? <Loader2 size={14} className="animate-spin" /> : <BookOpen size={14} />} {story ? "Regenerate" : "Generate match story"}</button>
          </div>
        </div>
        {!story && (
          <div className="glass mt-8 grid place-items-center p-16 text-center text-slate-400">
            Instead of hundreds of events, the AI picks the turning points, tactical shifts and key players.<br />
            {insights.length} insights available so far — generate at any time, even mid-match.
          </div>
        )}
        {story && (
          <>
            <h2 className="label mb-3 mt-8">5 moments that changed the match</h2>
            <div className="grid grid-cols-5 gap-3">
              {story.moments.map((m: any, i: number) => (
                <motion.button key={m.moment_id} initial={{ opacity: 0, y: 20 }} animate={{ opacity: 1, y: 0 }} transition={{ delay: i * 0.08 }}
                  onClick={() => { const ins = insights.find((x) => x.insight_id === m.moment_id); if (ins) replayInsight(ins); }}
                  className="glass group relative overflow-hidden p-4 text-left transition hover:-translate-y-1 hover:shadow-glow">
                  <div className="absolute -right-2 -top-4 font-display text-7xl font-bold text-white/[0.04]">{i + 1}</div>
                  <div className="font-mono text-xs text-cyan-300">{m.clock}</div>
                  <div className="mt-1"><Badge category={m.category} /></div>
                  <div className="mt-2 font-display text-[15px] font-semibold leading-snug text-white">{m.title}</div>
                  <div className="mt-1.5 text-[12px] leading-relaxed text-slate-400">{m.why_it_mattered}</div>
                  <div className="mt-2 text-[10px] text-cyan-300 opacity-0 transition group-hover:opacity-100">Replay in 3D →</div>
                </motion.button>
              ))}
            </div>
            <div className="mt-6 grid grid-cols-3 gap-3">
              <Card icon={<Target size={16} />} title="How the match was won" className="col-span-2">{story.how_won}</Card>
              <Card icon={<Crown size={16} />} title="Player of the match — AI explanation">
                {potm && <div className="mb-2"><div className="font-display text-xl font-bold text-white">{potm.name}</div>
                  <div className="text-[12px]" style={{ color: teams[potm.team_id]?.colors.primary }}>{teams[potm.team_id]?.name} · {potm.position} · influence {potm.influence}</div></div>}
                {story.potm_explanation}
              </Card>
              <Card icon={<Swords size={16} />} title="Tactical battle" className="col-span-2">{story.tactical_battle}</Card>
              <Card icon={<Target size={16} />} title="Biggest missed opportunity">
                {story.missed_opportunity}
                {story.facts.biggest_missed_opportunity && <div className="mt-2 font-mono text-[11px] text-yellow-300">xG {story.facts.biggest_missed_opportunity.xg} · {story.facts.biggest_missed_opportunity.clock}</div>}
              </Card>
            </div>
            <h2 className="label mb-2 mt-6">Goals</h2>
            <div className="flex gap-2">
              {story.facts.goals.map((g: any) => <div key={g.event_id} className="chip text-[12px]"><span className="font-mono text-cyan-300">{g.clock}</span> {g.scorer} ({g.team}){g.assist ? ` · assist ${g.assist}` : ""} · xG {g.xg}</div>)}
            </div>
          </>
        )}
      </div>
    </div>
  );
}

function Card({ icon, title, children, className }: { icon: React.ReactNode; title: string; children: React.ReactNode; className?: string }) {
  return (
    <div className={`glass p-5 ${className ?? ""}`}>
      <div className="mb-2 flex items-center gap-2 text-cyan-300">{icon}<span className="label text-cyan-300">{title}</span></div>
      <div className="text-[14px] leading-relaxed text-slate-200">{children}</div>
    </div>
  );
}
